/** Deterministic, opt-in CSS serialization from the pure foundation; no filesystem, document mutation or font loading. */
import { THEME_DARK_COLORS } from './theme-colors';
import { THEME_LEGACY_CHART_COLORS, THEME_MODE_COMPONENT_PAINT, THEME_PUBLIC_INHERITED_PAINT } from './theme-compatibility';
import { THEME_DARK_ELEVATION, THEME_DENSITY_TOKENS } from './theme-foundation';
import { resolveThemeMotion } from './theme-motion';
import { createThemeDeclarations } from './theme-tokens';
import { assertThemeTokenValue } from './theme-validation';
import { renderTypographyCss } from './theme-typography';
import { THEME_FLOATING_BUTTON_GROUP_PAINT } from './theme-floating-button-group';
import type { ThemeTokenMap } from './theme-types';

const SCOPE = '[data-zero-theme="next"]';

/** Stable alphabetical declarations for build parity and reviewable generated files. */
export function serializeThemeDeclarations(tokens: ThemeTokenMap): string {
  return Object.keys(tokens).sort().map(name => {
    assertThemeTokenValue(name, tokens[name]);
    return `  ${name}: ${tokens[name]};`;
  }).join('\n');
}
function rule(selector: string, tokens: ThemeTokenMap, extra = ''): string {
  return `${selector} {\n${serializeThemeDeclarations(tokens)}${extra ? `\n  ${extra}` : ''}\n}`;
}

/**
 * Produce the supplementary next stylesheet. Only explicit next boundaries and
 * their density/passive public sub-boundaries receive declarations; legacy siblings and
 * the legacy entrypoint are untouched. Modes have explicit precedence over an
 * ancestor .dark class. Tailwind's old dark utilities remain an adoption gate.
 */
export function renderThemeFoundationCss(): string {
  const dark = { ...THEME_DARK_COLORS, ...THEME_DARK_ELEVATION, ...THEME_LEGACY_CHART_COLORS.dark, ...THEME_MODE_COMPONENT_PAINT.dark,
    ...THEME_FLOATING_BUTTON_GROUP_PAINT.dark };
  const reduced = resolveThemeMotion({ reducedMotion: true }).tokens;
  return [
    '/* Generated by renderThemeFoundationCss(). Opt-in supplement; do not replace or delete globals.css. */',
    // One target attribute beats inherited declarations and ties legacy :root/.dark without inflating context specificity.
    rule(`:where(${SCOPE})[data-zero-theme]`, createThemeDeclarations(), 'color-scheme: light;'),
    rule(`:where(.dark ${SCOPE}:not([data-zero-mode]), ${SCOPE}.dark:not([data-zero-mode]), ${SCOPE}[data-zero-mode="dark"])[data-zero-theme]`, dark, 'color-scheme: dark;'),
    '@media (prefers-color-scheme: dark) {\n' + rule(`:where(${SCOPE}[data-zero-mode="system"])[data-zero-theme]`, dark, 'color-scheme: dark;') + '\n}',
    // Passive density/public regions inherit aliases and local overrides; only a new theme boundary rebinds them.
    ...Object.entries(THEME_DENSITY_TOKENS).map(([density, tokens]) =>
      rule(`:where(${SCOPE}[data-zero-density="${density}"], ${SCOPE} [data-zero-density="${density}"])[data-zero-density]`, tokens)),
    // Imported legacy public styles restate only these paints. Inherit keeps local customizations and avoids resetting geometry.
    rule(`:where(${SCOPE} .zero-public, ${SCOPE} .zero-public-page, ${SCOPE} [data-zero-surface="public"], ${SCOPE} [data-zero-page="public"])` +
      `:where(:not([data-zero-theme])):is(.zero-public, .zero-public-page, [data-zero-surface], [data-zero-page])`, THEME_PUBLIC_INHERITED_PAINT),
    '@media (pointer: coarse) {\n' + rule(`:where(${SCOPE}, ${SCOPE} [data-zero-density]):is([data-zero-theme], [data-zero-density])`, {
      '--zero-theme-hit-target-min': '2.75rem',
    }) + '\n' + rule(`:where(${SCOPE})[data-zero-theme]`, { '--zero-theme-modal-close-target': '44px' }) + '\n}',
    '@media (prefers-reduced-motion: reduce) {\n' + rule(`:where(${SCOPE})[data-zero-theme]`, reduced) + '\n}',
    // Unmarked legacy siblings stay unchanged; explicit text roles remain usable without a new provider.
    renderTypographyCss(),
    '',
  ].join('\n\n').trimEnd() + '\n';
}
