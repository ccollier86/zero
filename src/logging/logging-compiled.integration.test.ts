/** Real compiled dedicated workers, forced owner death, orphan fencing and retained commit replay. Synthetic files only. */
import { expect, test } from 'bun:test';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

test('compiled logging workers preserve an acknowledged commit across owner SIGKILL and deduplicate exact replay', async () => {
  const buildBase = '/Volumes/code-bank/build/zero-platform'; await mkdir(buildBase, { recursive: true });
  const build = await mkdtemp(join(buildBase, 'logging-compiled-')), root = await mkdtemp(join(tmpdir(), 'logging-compiled-crash-'));
  const actor = join(build, 'logging-actor'), fixture = fileURLToPath(new URL('./test-support/logging-crash-owner.fixture.ts', import.meta.url));
  let owner: ReturnType<typeof Bun.spawn> | null = null, replacement: ReturnType<typeof Bun.spawn> | null = null;
  try {
    // Parent and child import exactly the same realm/build. Separate builds
    // must not bypass Fabric's implementation fingerprint check.
    const compiler = Bun.spawn([process.execPath, '--no-env-file', 'build', fixture, '--compile', '--outfile', actor], { stdout: 'pipe', stderr: 'pipe' });
    const [compilerCode, compilerError] = await Promise.all([boundedExit(compiler, 60000), new Response(compiler.stderr).text(), new Response(compiler.stdout).text()]);
    expect(compilerCode, compilerError).toBe(0);
    owner = Bun.spawn([actor, root, actor], { stdin: 'ignore', stdout: 'ignore', stderr: 'ignore',
      env: { PATH: process.env.PATH, TMPDIR: tmpdir(), BUN_INSTALL_CACHE_DIR: '/Volumes/code-bank/caches/bun/install-cache' } });
    const deadline = Date.now() + 20000;
    while (!await Bun.file(join(root, 'committed')).exists() && Date.now() < deadline && owner.exitCode === null) await Bun.sleep(25);
    const failure = await Bun.file(join(root, 'failure.json')).exists() ? await Bun.file(join(root, 'failure.json')).text() : 'Compiled owner did not become ready.';
    expect(await Bun.file(join(root, 'committed')).exists(), failure).toBe(true);
    owner.kill('SIGKILL'); await owner.exited;
    replacement = Bun.spawn([actor, root, actor, 'verify'], { stdin: 'ignore', stdout: 'ignore', stderr: 'ignore',
      env: { PATH: process.env.PATH, TMPDIR: tmpdir(), BUN_INSTALL_CACHE_DIR: '/Volumes/code-bank/caches/bun/install-cache' } });
    expect(await boundedExit(replacement, 20000)).toBe(0);
    expect(await Bun.file(join(root, 'verified.json')).json()).toEqual({ first: ['compiled-before-kill'], after: 1, duplicate: true, checked: 1, state: 'closed' });
  } finally {
    if (owner && owner.exitCode === null) { owner.kill('SIGKILL'); await owner.exited; }
    if (replacement && replacement.exitCode === null) { replacement.kill('SIGKILL'); await replacement.exited; }
    // Both directories were freshly generated by this test and contain only its disposable files.
    await rm(root, { recursive: true, force: true }); await rm(build, { recursive: true, force: true });
  }
}, 120000);

async function boundedExit(child: ReturnType<typeof Bun.spawn>, timeoutMs: number): Promise<number> {
  const timeout = setTimeout(() => child.kill('SIGKILL'), timeoutMs);
  try { return await child.exited; }
  finally { clearTimeout(timeout); }
}
